GAME_H = ["""
// The most m_gameEventData can hold.
inline constexpr std::size_t kEventDataMax = 1452;

// Writes the events back to back, each padded to a byte. False when a field is
// out of range or the result passes kEventDataMax.
[[nodiscard]] bool encodeEvents(std::span<const Event> events, std::vector<std::byte>& out);

struct EventsDecode {
    std::vector<Event> events;
    std::size_t consumed = 0; // bytes covered by `events`
    bool complete = false;    // every byte was an event
};

// Stops at the first event that does not decode; `complete` is then false.
[[nodiscard]] EventsDecode decodeEvents(std::span<const std::byte> data);
"""]

GAME_C = ["""bool encodeEvents(std::span<const Event> events, std::vector<std::byte>& out) {
    std::vector<std::byte> buffer(kEventDataMax + 8);
    BitWriter bits(buffer);
    for (const auto& event : events) {
        if (!writeEvent(bits, event) || !bits.align()) {
            return false;
        }
        if (bits.bytes() > kEventDataMax) {
            return false;
        }
    }
    buffer.resize(bits.bytes());
    out = std::move(buffer);
    return true;
}

EventsDecode decodeEvents(std::span<const std::byte> data) {
    EventsDecode result;
    BitReader bits(data);
    while (bits.consumedBytes() < data.size()) {
        Event event;
        if (!readEvent(bits, event) || !bits.align()) {
            return result;
        }
        result.events.push_back(std::move(event));
        result.consumed = bits.consumedBytes();
    }
    result.complete = true;
    return result;
}
"""]

