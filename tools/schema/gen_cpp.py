"""Generate the NNet protocol C++ from the client's type table:

    include/Kitsune/Net/Enums.h        the enums every family shares
    include/Kitsune/Net/Records.h      the structs System and Local events share (user info, lobby, game description)
    src/Net/RecordCodec.h              internal: write/read for the enums and records
    src/Net/Records.cpp
    include/Kitsune/Net/SystemEvent.h  NNet::System (base-port TCP)
    src/Net/SystemEvent.cpp
    include/Kitsune/Net/LocalEvent.h   NNet::Local (game-port UDP)
    src/Net/LocalEvent.cpp
    include/Kitsune/Net/GameEvent.h    NNet::Game (the stream inside e_turn)
    src/Net/GameEvent.cpp

Run it with KITSUNE_SC2_IMAGE set (tools/schema/README.md), then run clang-format on the generated files. The
output is the source of truth once it is committed; a diff after a re-run means the table or this tool changed.
"""
import os, re, struct
from events import *

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
KEYWORDS = set("alignas alignof and asm auto bool break case catch char class const continue default delete do double else enum explicit export extern false float for friend goto if inline int long mutable namespace new not operator or private protected public register return short signed sizeof static struct switch template this throw true try typedef typeid typename union unsigned using virtual void volatile while xor".split())
BANNER = "// Generated by tools/schema/gen_cpp.py from the client's type table."


def res(t):
    while TS[t]["kind"] == "alias":
        t = TS[t]["target"]
    return t


def strip_prefix(n):
    return n[1:] if re.match(r"^[STE][A-Z]", n) else n


def cpp_name(full):
    parts = full.split("::")
    last = parts[-1]
    if last == "Enum":
        return strip_prefix(parts[-2])
    if "_typeof_m_" in last:
        return strip_prefix(parts[-2]) + up(last.split("_typeof_m_")[1])
    if last.startswith("__subtypeof_m_"):
        return strip_prefix(parts[-2]) + up(last[len("__subtypeof_m_"):])
    if last == "SHeader":
        return parts[-2] + "Header"  # System::SHeader and Local::SHeader are different types
    return strip_prefix(last)


def field_name(m):
    if m == "SHeader":
        return "header"  # the client's header base of every System and Local event
    n = m[2:] if m.startswith("m_") else m
    n = n[:1].lower() + n[1:]
    return n + "_" if n in KEYWORDS else n


def arm_name(m):
    return up(m[2:] if m.startswith("m_") else m)


def enumerator(m):
    return up(m[2:] if m.startswith("e_") else m)


# ---- what to generate -------------------------------------------------------
GAME_EVENTS = [(i, EVENT_NAMES[i], EVENT_TYPE[i]) for i in sorted(EVENT_NAMES)]
SYSTEM_EVENTS = net_family("System")
LOCAL_EVENTS = net_family("Local")


def reach(roots):
    """Struct, choice, and enum types under `roots`, each after the types it uses."""
    seen, order = set(), []

    def reg(t):
        t = res(t)
        ty = TS[t]
        k = ty["kind"]
        if t in seen:
            return
        seen.add(t)
        if k == "optional":
            reg(ty["inner"])
        elif k == "array":
            reg(ty["elem"])
        elif k in ("struct", "choice"):
            for x in ty["types"]:
                reg(x)
        if k in ("struct", "choice", "enum"):
            order.append(t)

    for r in roots:
        reg(r)
    return order


game_reach = reach([t for _, _, t in GAME_EVENTS])
event_roots = {t for _, _, t in SYSTEM_EVENTS + LOCAL_EVENTS}
net_reach = reach([t for _, _, t in SYSTEM_EVENTS + LOCAL_EVENTS])
# Enums keep the order they had when the generator made one list: the game's, then the others.
ENUMS = [t for t in game_reach if TS[t]["kind"] == "enum"]
for _t in reach(sorted(event_roots)):
    if TS[_t]["kind"] == "enum" and _t not in ENUMS:
        ENUMS.append(_t)
RECORDS = [t for t in net_reach if TS[t]["kind"] != "enum" and t not in event_roots]
_game_roots = {t for _, _, t in GAME_EVENTS}
GAME_TYPES = [t for t in game_reach if TS[t]["kind"] != "enum" and t not in set(RECORDS) and t not in _game_roots]

names = {}


def assign(types, used):
    for t in types:
        base = cpp_name(raw_name(t))
        n = base
        if n in used and used[n] != t:
            n = base + "_" + str(t)
        used[n] = t
        names[t] = n


_used_enums = {}
assign(ENUMS, _used_enums)
_used_net = dict(_used_enums)
assign(RECORDS + [t for _, _, t in SYSTEM_EVENTS] + [t for _, _, t in LOCAL_EVENTS], _used_net)
_used_game = dict(_used_enums)
assign(GAME_TYPES + [t for _, _, t in GAME_EVENTS], _used_game)
# The game's names sit inside kitsune::net, so one that matches a record it uses would hide it.
_clash = {names[t] for t in game_reach if t in set(RECORDS)} & {names[t] for t in GAME_TYPES + [t for _, _, t in GAME_EVENTS]}
if _clash:
    raise SystemExit("game type names hide records: %s" % sorted(_clash))


def int_type(lo, hi):
    if lo >= 0:
        for b in (8, 16, 32, 64):
            if hi < (1 << b):
                return "std::uint%d_t" % b
    for b in (8, 16, 32, 64):
        if -(1 << (b - 1)) <= lo and hi < (1 << (b - 1)):
            return "std::int%d_t" % b
    return "std::int64_t"


def ctype(t):
    t = res(t)
    ty = TS[t]
    k = ty["kind"]
    if k == "int":
        ln = ty["len"]
        return int_type(ln["min"], ln["max"])
    if k in ("u32", "u32b"):
        return "std::uint32_t"
    if k == "u64":
        return "std::uint64_t"
    if k == "bool":
        return "bool"
    if k == "string":
        return "std::string"
    if k in ("blob", "blobv"):
        return "std::vector<std::byte>"
    if k == "bitarray":
        return "std::vector<std::uint8_t>"
    if k == "array":
        return "std::vector<%s>" % ctype(ty["elem"])
    if k == "optional":
        return "std::optional<%s>" % ctype(ty["inner"])
    if k == "null":
        return "std::monostate"
    return names[t]


def lit(v):
    return ("INT64_C(%d)" % v) if v < 0 else ("UINT64_C(%d)" % v)


def write_file(rel, text):
    open(os.path.join(REPO, *rel.split("/")), "w", encoding="utf-8", newline="\n").write(text)


def infix(vals):
    """The condition a raw value must meet to be a member of an enum."""
    contiguous = vals == list(range(vals[0], vals[-1] + 1))
    if contiguous and vals[0] == 0:
        return "raw <= %d" % vals[-1], "v <= %d" % vals[-1]
    if contiguous:
        return "raw >= %d && raw <= %d" % (vals[0], vals[-1]), "v >= %d && v <= %d" % (vals[0], vals[-1])
    return "(" + " || ".join("raw == %d" % v for v in vals) + ")", " || ".join("v == %d" % x for x in vals)


# ---- declarations -----------------------------------------------------------
def default_init(fr):
    tk = TS[fr]["kind"]
    if tk in ("int", "u32", "u32b", "u64"):
        return " = %d" % (TS[fr]["len"]["min"] if tk == "int" else 0)
    if tk == "bool":
        return " = false"
    if tk == "enum":
        return " = %s{%d}" % (names[fr], TS[fr]["values"][0])
    return ""


def decl(t, out):
    ty = TS[t]
    k = ty["kind"]
    n = names[t]
    if k == "struct":
        nm = members(t)[1:]
        out.append("// %s." % raw_name(t))
        out.append("struct %s {" % n)
        for i, ft in enumerate(ty["types"]):
            out.append("    %s %s%s;" % (ctype(ft), field_name(nm[i]), default_init(res(ft))))
        out.append("")
        out.append("    bool operator==(const %s&) const = default;" % n)
        out.append("};\n")
    elif k == "choice":
        nm = members(t)[1:]
        arms = []
        for i, ft in enumerate(ty["types"]):
            an = n + "Arm" + arm_name(nm[i])
            arms.append(an)
            fr = res(ft)
            out.append("// arm %d" % ty["values"][i])
            out.append("struct %s {" % an)
            if TS[fr]["kind"] != "null":
                init = ""
                if TS[fr]["kind"] in ("int", "u32", "u32b", "u64"):
                    init = " = %d" % (TS[fr]["len"]["min"] if TS[fr]["kind"] == "int" else 0)
                elif TS[fr]["kind"] == "bool":
                    init = " = false"
                out.append("    %s value%s;" % (ctype(ft), init))
                out.append("")
            out.append("    bool operator==(const %s&) const = default;" % an)
            out.append("};")
        out.append("using %s = std::variant<%s>;\n" % (n, ", ".join(arms)))


def enums_header():
    E = ["#pragma once", "", BANNER + " The enums of the NNet protocol that the base-port, game-port, and game-event types",
         "// use. Names are the client's, with the `E` type prefix and the `e_` enumerator prefix dropped. `isValid` is true",
         "// for the values the client accepts on the wire.", "", "#include <cstdint>", "", "namespace kitsune::net {", ""]
    for t in ENUMS:
        ty = TS[t]
        nm = members(t)[1:]
        E.append("// %s" % raw_name(t))
        E.append("enum class %s : std::uint8_t {" % names[t])
        for v, m in zip(ty["values"], nm):
            E.append("    %s = %d," % (enumerator(m), v))
        E.append("};\n")
        E.append("[[nodiscard]] constexpr bool isValid(%s value) noexcept {" % names[t])
        E.append("    const auto v = static_cast<unsigned>(value);")
        E.append("    return %s;" % infix(ty["values"])[1])
        E.append("}\n")
    E.append("} // namespace kitsune::net")
    return "\n".join(E) + "\n"


# ---- codecs -----------------------------------------------------------------
def gen_write(t, v, ind):
    t = res(t)
    ty = TS[t]
    k = ty["kind"]
    p = " " * ind
    if k == "int":
        ln = ty["len"]
        if ln["bits"] == 0:
            return ["%sif (%s != %d) return false;" % (p, v, ln["min"])]
        if ln["min"] < 0:
            return ["%sif (!writeSigned(bits, %s, %s, %s, %d)) return false;" % (p, v, lit(ln["min"]), lit(ln["max"]), ln["bits"])]
        return ["%sif (!writeUnsigned(bits, %s, %s, %s, %d)) return false;" % (p, v, lit(ln["min"]), lit(ln["max"]), ln["bits"])]
    if k in ("u32", "u32b"):
        return ["%sif (!bits.write(%s, 32)) return false;" % (p, v)]
    if k == "u64":
        return ["%sif (!bits.write(%s, 64)) return false;" % (p, v)]
    if k == "bool":
        return ["%sif (!writeBool(bits, %s)) return false;" % (p, v)]
    if k == "null":
        return []
    if k == "string":
        ln = ty["len"]
        return ["%sif (!writeString(bits, %s, %d, %s)) return false;" % (p, v, ln["bits"] - 2, lit(ln["max"] >> 2))]
    if k in ("blob", "blobv"):
        ln = ty["len"]
        if ln["fixed"]:
            return ["%sif (!writeFixedBlob(bits, %s, %d)) return false;" % (p, v, ln["min"])]
        return ["%sif (!writeBlob(bits, %s, %d, %s)) return false;" % (p, v, ln["bits"], lit(ln["max"]))]
    if k == "bitarray":
        ln = ty["len"]
        if ln["fixed"]:
            raise SystemExit("fixed bitarray")
        return ["%sif (!writeBitArray(bits, %s, %d, %s)) return false;" % (p, v, ln["bits"], lit(ln["max"]))]
    if k == "optional":
        out = ["%sif (!writeBool(bits, %s.has_value())) return false;" % (p, v), "%sif (%s) {" % (p, v)]
        out += gen_write(ty["inner"], "(*%s)" % v, ind + 4)
        out.append("%s}" % p)
        return out
    if k == "array":
        ln = ty["len"]
        out = []
        if ln["fixed"]:
            out.append("%sif (%s.size() != %d) return false;" % (p, v, ln["min"]))
        else:
            out.append("%sif (!writeUnsigned(bits, %s.size(), %s, %s, %d)) return false;" % (p, v, lit(ln["min"]), lit(ln["max"]), ln["bits"]))
        out.append("%sfor (const auto& item : %s) {" % (p, v))
        out += gen_write(ty["elem"], "item", ind + 4)
        out.append("%s}" % p)
        return out
    if k in ("struct", "choice", "enum"):
        return ["%sif (!write(bits, %s)) return false;" % (p, v)]
    raise SystemExit("write kind " + k)


def gen_read(t, v, ind):
    t = res(t)
    ty = TS[t]
    k = ty["kind"]
    p = " " * ind
    ct = ctype(t)
    if k == "int":
        ln = ty["len"]
        if ln["bits"] == 0:
            return ["%s%s = %d;" % (p, v, ln["min"])]
        if ln["min"] < 0:
            return ["%s{" % p, "%s    std::int64_t raw = 0;" % p, "%s    if (!readSigned(bits, raw, %s, %s, %d)) return false;" % (p, lit(ln["min"]), lit(ln["max"]), ln["bits"]),
                    "%s    %s = static_cast<%s>(raw);" % (p, v, ct), "%s}" % p]
        return ["%s{" % p, "%s    std::uint64_t raw = 0;" % p, "%s    if (!readUnsigned(bits, raw, %s, %s, %d)) return false;" % (p, lit(ln["min"]), lit(ln["max"]), ln["bits"]),
                "%s    %s = static_cast<%s>(raw);" % (p, v, ct), "%s}" % p]
    if k in ("u32", "u32b", "u64"):
        w = 64 if k == "u64" else 32
        return ["%s{" % p, "%s    std::uint64_t raw = 0;" % p, "%s    if (!bits.read(raw, %d)) return false;" % (p, w), "%s    %s = static_cast<%s>(raw);" % (p, v, ct), "%s}" % p]
    if k == "bool":
        return ["%sif (!readBool(bits, %s)) return false;" % (p, v)]
    if k == "null":
        return []
    if k == "string":
        ln = ty["len"]
        return ["%sif (!readString(bits, %s, %d, %s)) return false;" % (p, v, ln["bits"] - 2, lit(ln["max"] >> 2))]
    if k in ("blob", "blobv"):
        ln = ty["len"]
        if ln["fixed"]:
            return ["%s%s.assign(%d, std::byte{0});" % (p, v, ln["min"]), "%sif (!readFixedBlob(bits, %s)) return false;" % (p, v)]
        return ["%sif (!readBlob(bits, %s, %d, %s)) return false;" % (p, v, ln["bits"], lit(ln["max"]))]
    if k == "bitarray":
        ln = ty["len"]
        return ["%sif (!readBitArray(bits, %s, %d, %s)) return false;" % (p, v, ln["bits"], lit(ln["max"]))]
    if k == "optional":
        out = ["%s{" % p, "%s    bool present = false;" % p, "%s    if (!readBool(bits, present)) return false;" % p, "%s    if (present) {" % p,
               "%s        %s.emplace();" % (p, v)]
        out += gen_read(ty["inner"], "(*%s)" % v, ind + 8)
        out += ["%s    } else {" % p, "%s        %s.reset();" % (p, v), "%s    }" % p, "%s}" % p]
        return out
    if k == "array":
        ln = ty["len"]
        out = ["%s{" % p, "%s    std::uint64_t n = 0;" % p]
        if ln["fixed"]:
            out.append("%s    n = %d;" % (p, ln["min"]))
        else:
            out.append("%s    if (!readUnsigned(bits, n, %s, %s, %d)) return false;" % (p, lit(ln["min"]), lit(ln["max"]), ln["bits"]))
        out += ["%s    %s.assign(static_cast<std::size_t>(n), %s{});" % (p, v, ctype(ty["elem"])), "%s    for (auto& item : %s) {" % (p, v)]
        out += gen_read(ty["elem"], "item", ind + 8)
        out += ["%s    }" % p, "%s}" % p]
        return out
    if k in ("struct", "choice", "enum"):
        return ["%sif (!read(bits, %s)) return false;" % (p, v)]
    raise SystemExit("read kind " + k)


def prototypes(types):
    out = []
    for t in types:
        out.append("[[nodiscard]] bool write(BitWriter& bits, const %s& value);" % names[t])
        out.append("[[nodiscard]] bool read(BitReader& bits, %s& value);" % names[t])
    return out


def codec(t, out):
    ty = TS[t]
    k = ty["kind"]
    n = names[t]
    nm = members(t)[1:] if k in ("struct", "choice") else []
    if k == "enum":
        tg = ty["tag"]
        cond = infix(ty["values"])[0]
        out.append("bool write(BitWriter& bits, const %s& value) {" % n)
        out.append("    const auto raw = static_cast<std::uint64_t>(value);")
        out.append("    return %s && writeUnsigned(bits, raw, %s, %s, %d);" % (cond, lit(tg["min"]), lit(tg["max"]), tg["bits"]))
        out.append("}\n")
        out.append("bool read(BitReader& bits, %s& value) {" % n)
        out.append("    std::uint64_t raw = 0;")
        out.append("    if (!readUnsigned(bits, raw, %s, %s, %d)) return false;" % (lit(tg["min"]), lit(tg["max"]), tg["bits"]))
        out.append("    if (!(%s)) return false;" % cond)
        out.append("    value = static_cast<%s>(raw);" % n)
        out.append("    return true;")
        out.append("}\n")
    elif k == "struct":
        out.append("bool write(BitWriter& bits, const %s& value) {" % n)
        if not ty["types"]:
            out += ["    (void)bits;", "    (void)value;"]
        for i, ft in enumerate(ty["types"]):
            out += gen_write(ft, "value." + field_name(nm[i]), 4)
        out.append("    return true;")
        out.append("}\n")
        out.append("bool read(BitReader& bits, %s& value) {" % n)
        if not ty["types"]:
            out += ["    (void)bits;", "    (void)value;"]
        for i, ft in enumerate(ty["types"]):
            out += gen_read(ft, "value." + field_name(nm[i]), 4)
        out.append("    return true;")
        out.append("}\n")
    elif k == "choice":
        tg = ty["tag"]
        out.append("bool write(BitWriter& bits, const %s& value) {" % n)
        out.append("    std::uint64_t tag = 0;")
        out.append("    switch (value.index()) {")
        for i, v in enumerate(ty["values"]):
            out.append("    case %d: tag = %s; break;" % (i, lit(v)))
        out.append("    default: return false;")
        out.append("    }")
        out.append("    if (!writeUnsigned(bits, tag, %s, %s, %d)) return false;" % (lit(tg["min"]), lit(tg["max"]), tg["bits"]))
        out.append("    switch (value.index()) {")
        for i, ft in enumerate(ty["types"]):
            out.append("    case %d: {" % i)
            if TS[res(ft)]["kind"] == "null":
                out.append("        break;")
            else:
                out.append("        const auto& arm = std::get<%d>(value);" % i)
                out += gen_write(ft, "arm.value", 8)
                out.append("        break;")
            out.append("    }")
        out.append("    default: return false;")
        out.append("    }")
        out.append("    return true;")
        out.append("}\n")
        out.append("bool read(BitReader& bits, %s& value) {" % n)
        out.append("    std::uint64_t tag = 0;")
        out.append("    if (!readUnsigned(bits, tag, %s, %s, %d)) return false;" % (lit(tg["min"]), lit(tg["max"]), tg["bits"]))
        out.append("    switch (tag) {")
        for i, v in enumerate(ty["values"]):
            out.append("    case %s: {" % lit(v))
            out.append("        auto& arm = value.emplace<%d>();" % i)
            if TS[res(ty["types"][i])]["kind"] == "null":
                out.append("        (void)arm;")
            else:
                out += gen_read(ty["types"][i], "arm.value", 8)
            out.append("        return true;")
            out.append("    }")
        out.append("    default: return false;")
        out.append("    }")
        out.append("}\n")


# ---- Records ----------------------------------------------------------------
def records_files():
    H = ["#pragma once", "", BANNER, "//",
         "// The structs the NNet::System and NNet::Local events share, with the client's names (the `S`, `T`, and",
         "// `C` type prefixes and the `m_` member prefix dropped for the first two). A choice is a variant with one",
         "// struct per arm, named after the choice and the arm. Two types carry their namespace, because the client",
         "// has a `SHeader` in each: SystemHeader and LocalHeader.", "",
         "#include <cstddef>", "#include <cstdint>", "#include <optional>", "#include <string>", "#include <variant>",
         "#include <vector>", "", '#include "Kitsune/Net/Enums.h"', "", "namespace kitsune::net {", ""]
    for t in RECORDS:
        decl(t, H)
    H.append("} // namespace kitsune::net")

    P = ["#pragma once", "", BANNER, "// Internal: the field codecs of the enums and records, shared by the event families.", "",
         '#include "BitPack.h"', '#include "Kitsune/Net/Enums.h"', '#include "Kitsune/Net/Records.h"', "", "namespace kitsune::net {", ""]
    P += prototypes(ENUMS + RECORDS)
    P += ["", "} // namespace kitsune::net"]

    C = [BANNER, "", '#include "RecordCodec.h"', "", "namespace kitsune::net {", ""]
    for t in ENUMS + RECORDS:
        codec(t, C)
    C.append("} // namespace kitsune::net")
    write_file("include/Kitsune/Net/Records.h", "\n".join(H) + "\n")
    write_file("src/Net/RecordCodec.h", "\n".join(P) + "\n")
    write_file("src/Net/Records.cpp", "\n".join(C) + "\n")


# ---- families of events -----------------------------------------------------
def family_files(key, events, bits, label, id_enum, variant, ns_open, ns_close, doc, extra_h, extra_c, extra_includes=()):
    """Header and source for one family. `key` is System, Local, or Game; the id enum and the variant are named
    after it (Game keeps the plain EventId and Event, inside its own namespace)."""
    fn = {"System": "system", "Local": "local", "Game": ""}[key]
    id_fn = (fn + "EventId") if fn else "eventId"
    name_fn = (fn + "EventName") if fn else "eventName"
    event_ts = [t for _, _, t in events]
    H = ["#pragma once", "", BANNER, "//"] + doc + [
        "", "#include <cstddef>", "#include <cstdint>", "#include <optional>", "#include <span>", "#include <string>",
        "#include <variant>", "#include <vector>", "", '#include "Kitsune/Net/Records.h"', ""] + [ns_open, ""]
    H.append("// %s. %d bits on the wire." % (label, bits))
    H.append("enum class %s : std::uint8_t {" % id_enum)
    for i, e, t in events:
        H.append("    %s = %d," % (enumerator(e), i))
    H.append("};\n")
    for t in (GAME_TYPES if key == "Game" else []):
        decl(t, H)
    for t in event_ts:
        decl(t, H)
    H.append("// One struct per event id; the id is the variant's index in id order (see %s)." % id_fn)
    H.append("using %s = std::variant<%s>;\n" % (variant, ", ".join(names[t] for t in event_ts)))
    H.append("// The id of the event a variant holds.")
    H.append("[[nodiscard]] %s %s(const %s& event) noexcept;" % (id_enum, id_fn, variant))
    H.append("[[nodiscard]] const char* %s(%s id) noexcept;" % (name_fn, id_enum))
    H += extra_h
    H.append(ns_close + "\n")

    C = [BANNER, "", '#include "Kitsune/Net/%sEvent.h"' % key, "", "#include <utility>", "", '#include "RecordCodec.h"', "", ns_open, "", "namespace {", ""]
    own = (GAME_TYPES if key == "Game" else []) + event_ts
