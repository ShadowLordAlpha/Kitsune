"""Write the test fixtures in tests/fixtures that come from the type table and from a capture.

  game_event_vectors.h   every NNet::Game event id, from the reference encoder
  net_event_vectors.h    every NNet::System (base port) and NNet::Local (game port) event id
  game_event_capture.h   game-event blobs from a capture of two official clients (needs KITSUNE_CAPTURE)

The vectors are seeded, so a re-run gives the same bytes. Needs KITSUNE_SC2_IMAGE; see README.md.
"""
import os
import random

from events import *
from pcap import event_blobs
from refcodec import W, encode, event_bytes, rnd, vectors

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "tests", "fixtures")
TOOL = "tools/schema/make_fixtures.py"


def arr(name, b):
    lines = ["inline constexpr std::uint8_t %s[] = {" % name]
    for i in range(0, len(b), 12):
        lines.append("    " + ", ".join("0x%02x" % x for x in b[i:i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines)


def write(name, lines):
    with open(os.path.join(OUT, name), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def game_vectors():
    L = ["#pragma once", "",
         "// Generated by %s." % TOOL,
         "// One to three encoded events per NNet::Game event id (docs/game-events.md), made by an independent",
         "// encoder written from the client's type table, with boundary and random values. The events that",
         "// replays also contain were decoded again by Blizzard's s2protocol with identical values.",
         "", "#include <cstddef>", "#include <cstdint>", "", "namespace kitsune::fixtures {", "",
         "struct EventVector {", "    std::uint8_t id;", "    const std::uint8_t* data;", "    std::size_t size;", "};", ""]
    names = []
    for n, (eid, val, data) in enumerate(vectors(per=3)):
        nm = "kVec%03d_%d" % (eid, n)
        L += [arr(nm, data), ""]
        names.append((eid, nm))
    L.append("inline constexpr EventVector kEventVectors[] = {")
    L += ["    {%d, %s, sizeof %s}," % (eid, nm, nm) for eid, nm in names]
    L += ["};", "", "} // namespace kitsune::fixtures"]
    write("game_event_vectors.h", L)
    return len(names)


def net_vectors():
    L = ["#pragma once", "",
         "// Generated by %s." % TOOL,
         "// One to three encoded datagrams per NNet::System (base-port TCP) and NNet::Local (game-port UDP)",
         "// event id, made by an independent encoder written from the client's type table, with boundary and",
         "// random values. docs/game-events.md, \"Checking the codecs\".", "",
         "#include <cstddef>", "#include <cstdint>", "", "namespace kitsune::fixtures {", "",
         "struct NetVector {", "    std::uint8_t id;", "    const std::uint8_t* data;", "    std::size_t size;", "};", ""]
    total = 0
    for ns, bits, seed in (("System", 6, 410), ("Local", 4, 75689)):
        r = random.Random(seed)
        names = []
        n = 0
        for i, e, t in net_family(ns):
            for _ in range(3):
                w = W()
                w.write(i, bits)
                encode(w, t, rnd(t, r))
                w.align()
                nm = "k%s%02d_%d" % (ns, i, n)
                L += [arr(nm, w.data()), ""]
                names.append((i, nm))
                n += 1
        L.append("inline constexpr NetVector k%sVectors[] = {" % ns)
        L += ["    {%d, %s, sizeof %s}," % (i, nm, nm) for i, nm in names]
        L += ["};", ""]
        total += n
    L.append("} // namespace kitsune::fixtures")
    write("net_event_vectors.h", L)
    return total


CAPTURE_PICKS = [
    ("kSetLobbySlot", ("guest", 21), "guest takes slot 1 and sets its race"),
    ("kStartGame", ("host", 23), "host starts the game"),
    ("kHostLoadPackage", ("host", 25), "host: sync loading time, unpause, sound lengths, options, finished loading"),
    ("kGuestLoadPackage", ("guest", 25), "guest: the same without the sync loading time"),
    ("kUserFinishedLoading", ("host", 27), "one event, no fields"),
    ("kHostFirstCommands", ("host", 29), "host: sync playing time, then the first commands"),
    ("kGuestFirstCommands", ("guest", 29), "guest: the first commands"),
    ("kCameraUpdate", ("guest", 30), "a camera update"),
    ("kGuestSmall", ("guest", 199), "selection, command manager state, selection"),
    ("kHostTargets", ("host", 399), "selections, a target point, command manager state"),
]


def capture_blobs(pcap):
    first = {}
    for _, who, seq, data in event_blobs(pcap):
        first.setdefault((who, seq), data)
    L = ["#pragma once", "",
         "// Generated by %s from a capture of two official clients in one game (docs/tcp-base.md," % TOOL,
         "// \"Session order\"): the m_gameEventData of single turns, byte for byte.", "",
         "#include <cstdint>", "", "namespace kitsune::fixtures {", ""]
    for name, key, note in CAPTURE_PICKS:
        d = first[key]
        L += ["// %s (%s turn %d, %d bytes)." % (note, key[0], key[1], len(d)), arr(name, d), ""]
    L.append("} // namespace kitsune::fixtures")
    write("game_event_capture.h", L)
    return len(CAPTURE_PICKS)


if __name__ == "__main__":
    print("game event vectors:", game_vectors())
    print("system and local vectors:", net_vectors())
    pcap = os.environ.get("KITSUNE_CAPTURE")
    if pcap:
        print("captured blobs:", capture_blobs(pcap))
    else:
        print("KITSUNE_CAPTURE not set; game_event_capture.h left as it is")
